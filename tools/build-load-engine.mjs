// Copies the shared faculty-load engine (the LOAD-ENGINE:START … END block in
// index.html) into the load-alerts edge function as an ES module, so the hourly
// server check computes loads exactly like the browser.
//
//   node tools/build-load-engine.mjs
//
// Then redeploy supabase/functions/load-alerts (index.ts + engine.js).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const html = readFileSync(join(root, "index.html"), "utf8");
const m = /\/\* LOAD-ENGINE:START \*\/\n([\s\S]*?)\/\* LOAD-ENGINE:END \*\//.exec(html);
if (!m) throw new Error("LOAD-ENGINE block not found in index.html");
const out = join(root, "supabase/functions/load-alerts/engine.js");
// Every top-level function/const, so the edge function can fingerprint the code it
// is actually running (engineFingerprint) and we can compare with this build.
const names = [...m[1].matchAll(/^(?:function\s+(\w+)\s*\(|const\s+(\w+)\s*=)/gm)].map(x => x[1] || x[2]);
writeFileSync(out,
  "// GENERATED by tools/build-load-engine.mjs from index.html (LOAD-ENGINE block). Do not edit.\n" +
  "// deno-lint-ignore-file\n" +
  m[1] +
  "\nexport { _ldCompute, _ldOverBy, _ldMadeLabels, _ldFhIndex, _LD_DEFAULTS, canonicalCourseCode };\n" +
  `export const _ldEngineParts = { ${names.join(", ")} };\n` +
  "// SHA-256 over every part's source (functions) or JSON (data) — same in Node and Deno.\n" +
  "export async function engineFingerprint() {\n" +
  "  const txt = Object.entries(_ldEngineParts).map(([k, v]) => k + \"=\" + (typeof v === \"function\" ? v.toString()\n" +
  "    : JSON.stringify(v, (_k, x) => x instanceof Set ? [...x] : x))).join(\"\\n\");\n" +
  "  const buf = await crypto.subtle.digest(\"SHA-256\", new TextEncoder().encode(txt));\n" +
  "  return [...new Uint8Array(buf)].map(b => b.toString(16).padStart(2, \"0\")).join(\"\");\n" +
  "}\n");
console.log(`wrote ${out} (${m[1].length} chars)`);
